create extension if not exists pgcrypto with schema extensions;  -- password hashing

-- ---------------------------------------------------------------------------
-- Logins (never readable through the API)

-- A username + hashed password, plus a hashed one-time recovery code.
create table app_users (
  id            uuid primary key default gen_random_uuid(),
  username      text not null unique check (username ~ '^[a-z0-9_.]{3,30}$'),
  password_hash text not null,
  recovery_hash text,                          -- for "Forgot password?"
  is_admin      boolean not null default false, -- can see the Reports screen
  created_at    timestamptz not null default now()
);

-- A logged-in browser. The app keeps the token so a refresh stays logged in.
create table app_sessions (
  token      uuid primary key default gen_random_uuid(),
  user_id    uuid not null references app_users(id) on delete cascade,
  created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Profiles (public: other students browse these)

-- A person using the app
create table students (
  id                      uuid primary key default gen_random_uuid(),
  user_id                 uuid unique references app_users(id) on delete cascade, -- null for sample students
  full_name               text not null,
  avatar_color            text not null default '#24543f' check (avatar_color ~ '^#[0-9a-f]{6}$'),
  program_status          text not null check (program_status in ('pre_is', 'is_core', 'is_minor', 'ta')),
  graduation_year         int check (graduation_year between 2020 and 2040),
  looking_for_help_with   text,                 -- optional note; the tags are in student_needs
  ask_me_about            text,                 -- icebreaker shown on the profile
  bio                     text,
  contact_setting         text not null default 'courses'
                          check (contact_setting in ('anyone', 'courses', 'friends')), -- who can message / invite me
  availability_updated_at timestamptz,
  last_active_at          timestamptz,
  created_at              timestamptz not null default now()
);

-- An IS topic: listed as a strength (student_skills) or a need (student_needs)
create table skills (
  id   bigint generated by default as identity primary key,
  name text not null unique
);

-- An IS class, e.g. IS 201
create table courses (
  id   bigint generated by default as identity primary key,
  code text not null unique,
  name text not null
);

-- Join tables: students <-> skills they're strong in, classes they take, topics they need help with
create table student_skills (
  student_id uuid   not null references students(id) on delete cascade,
  skill_id   bigint not null references skills(id)   on delete cascade,
  primary key (student_id, skill_id)
);
create table student_courses (
  student_id uuid   not null references students(id) on delete cascade,
  course_id  bigint not null references courses(id)  on delete cascade,
  primary key (student_id, course_id)
);
create table student_needs (
  student_id uuid   not null references students(id) on delete cascade,
  skill_id   bigint not null references skills(id)   on delete cascade,
  primary key (student_id, skill_id)
);

-- Weekly time a student is free to study (Availability screen)
create table availability_slots (
  id               bigint generated by default as identity primary key,
  student_id       uuid not null references students(id) on delete cascade,
  day_of_week      text not null check (day_of_week in ('Mon','Tue','Wed','Thu','Fri','Sat','Sun')),
  start_time       time not null,
  duration_minutes int  not null default 60 check (duration_minutes > 0)
);

-- Student-made study guide shared with others (Study Resources screen)
create table study_resources (
  id           bigint generated by default as identity primary key,
  uploader_id  uuid not null references students(id) on delete cascade,
  title        text not null,
  course       text,                          -- a courses.code, e.g. 'IS 201'
  resource_url text not null,
  uploaded_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Private: only reachable through the functions in functions.sql

-- Friend connection between two students
create table friendships (
  id           bigint generated by default as identity primary key,
  requester_id uuid not null references students(id) on delete cascade,
  addressee_id uuid not null references students(id) on delete cascade,
  status       text not null default 'pending' check (status in ('pending', 'accepted')),
  created_at   timestamptz not null default now(),
  unique (requester_id, addressee_id),
  check (requester_id <> addressee_id)
);

-- One-on-one chat message
create table messages (
  id           bigint generated by default as identity primary key,
  sender_id    uuid not null references students(id) on delete cascade,
  recipient_id uuid not null references students(id) on delete cascade,
  body         text not null check (length(body) between 1 and 2000),
  sent_at      timestamptz not null default now(),
  read_at      timestamptz
);

-- A first message from someone who isn't a friend waits here until accepted
create table message_requests (
  sender_id    uuid not null references students(id) on delete cascade,
  recipient_id uuid not null references students(id) on delete cascade,
  status       text not null default 'pending' check (status in ('pending', 'accepted', 'declined')),
  created_at   timestamptz not null default now(),
  primary key (sender_id, recipient_id)
);

-- Study session between two students (Set Up / Confirm Meetup screens)
create table meetups (
  id                 bigint generated by default as identity primary key,
  requester_id       uuid not null references students(id) on delete cascade,
  partner_id         uuid not null references students(id) on delete cascade,
  scheduled_at       timestamptz not null,
  duration_minutes   int not null default 60 check (duration_minutes between 15 and 240),
  topic              text,
  location           text not null,
  status             text not null default 'requested'
                     check (status in ('requested', 'confirmed', 'completed', 'cancelled')),
  requester_feedback text check (requester_feedback in ('great', 'okay', 'no_show')),
  partner_feedback   text check (partner_feedback in ('great', 'okay', 'no_show')),
  created_at         timestamptz not null default now()
);

-- Block of another student (Safety & Privacy screen)
create table user_blocks (
  id         bigint generated by default as identity primary key,
  blocker_id uuid not null references students(id) on delete cascade,
  blocked_id uuid not null references students(id) on delete cascade,
  is_report  boolean not null default false,
  reason     text,
  created_at timestamptz not null default now(),
  unique (blocker_id, blocked_id)
);

-- A report of a student or a study guide, reviewed by admins
create table reports (
  id          bigint generated by default as identity primary key,
  reporter_id uuid not null references students(id) on delete cascade,
  student_id  uuid references students(id) on delete cascade,
  resource_id bigint references study_resources(id) on delete cascade,
  reason      text not null,
  created_at  timestamptz not null default now(),
  resolved_at timestamptz,
  check ((student_id is null) <> (resource_id is null))
);

-- Study guides a student saved for later
create table saved_resources (
  student_id  uuid   not null references students(id) on delete cascade,
  resource_id bigint not null references study_resources(id) on delete cascade,
  primary key (student_id, resource_id)
);

-- Something that happened involving you (the bell)
create table notifications (
  id         bigint generated by default as identity primary key,
  student_id uuid not null references students(id) on delete cascade,
  kind       text not null,
  body       text not null,
  screen     text,                            -- where tapping it goes
  params     jsonb not null default '{}',
  created_at timestamptz not null default now(),
  read_at    timestamptz
);

-- A study group: one per course, or a group made by "Can't find anyone?" matching
create table study_groups (
  id         bigint generated by default as identity primary key,
  kind       text not null check (kind in ('course', 'match')),
  course_id  bigint references courses(id) on delete cascade,
  skill_id   bigint references skills(id) on delete cascade,
  name       text not null,
  created_at timestamptz not null default now()
);
create unique index one_group_per_course on study_groups (course_id) where kind = 'course';

create table group_members (
  group_id     bigint not null references study_groups(id) on delete cascade,
  student_id   uuid   not null references students(id) on delete cascade,
  joined_at    timestamptz not null default now(),
  last_read_at timestamptz not null default now(),
  primary key (group_id, student_id)
);

create table group_messages (
  id        bigint generated by default as identity primary key,
  group_id  bigint not null references study_groups(id) on delete cascade,
  sender_id uuid   not null references students(id) on delete cascade,
  body      text   not null check (length(body) between 1 and 2000),
  sent_at   timestamptz not null default now()
);

-- "Can't find anyone?": students waiting to be matched on a course or a topic
create table study_queue (
  id               bigint generated by default as identity primary key,
  student_id       uuid not null references students(id) on delete cascade,
  course_id        bigint references courses(id) on delete cascade,
  skill_id         bigint references skills(id) on delete cascade,
  created_at       timestamptz not null default now(),
  matched_group_id bigint references study_groups(id) on delete set null,
  check ((course_id is null) <> (skill_id is null))
);

