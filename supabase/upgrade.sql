-- Move the old single "current course" text into the new classes list.
do $$ begin
  if exists (select 1 from information_schema.columns
             where table_schema = 'public' and table_name = 'students' and column_name = 'current_course') then
    insert into courses (code, name)
      select distinct x.code, x.code from (
        select regexp_replace(upper(trim(current_course)), '^IS\s*(\d{3})$', 'IS \1') as code from students
      ) x where x.code ~ '^IS \d{3}$'
    on conflict (code) do nothing;
    insert into student_courses (student_id, course_id)
      select s.id, c.id from students s
      join courses c on c.code = regexp_replace(upper(trim(s.current_course)), '^IS\s*(\d{3})$', 'IS \1')
    on conflict do nothing;
  end if;
end $$;
