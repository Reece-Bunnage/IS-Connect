-- New tables (same definitions as schema.sql)
create table if not exists courses (
  id   bigint generated by default as identity primary key,
  code text not null unique,
  name text not null
);
create table if not exists student_courses (
  student_id uuid   not null references students(id) on delete cascade,
  course_id  bigint not null references courses(id)  on delete cascade,
  primary key (student_id, course_id)
);
create table if not exists student_needs (
  student_id uuid   not null references students(id) on delete cascade,
  skill_id   bigint not null references skills(id)   on delete cascade,
  primary key (student_id, skill_id)
);
create table if not exists message_requests (
  sender_id    uuid not null references students(id) on delete cascade,
  recipient_id uuid not null references students(id) on delete cascade,
  status       text not null default 'pending' check (status in ('pending', 'accepted', 'declined')),
  created_at   timestamptz not null default now(),
  primary key (sender_id, recipient_id)
);
create table if not exists reports (
  id          bigint generated by default as identity primary key,
  reporter_id uuid not null references students(id) on delete cascade,
  student_id  uuid references students(id) on delete cascade,
  resource_id bigint references study_resources(id) on delete cascade,
  reason      text not null,
  created_at  timestamptz not null default now(),
  resolved_at timestamptz,
  check ((student_id is null) <> (resource_id is null))
);
create table if not exists saved_resources (
  student_id  uuid   not null references students(id) on delete cascade,
  resource_id bigint not null references study_resources(id) on delete cascade,
  primary key (student_id, resource_id)
);
create table if not exists notifications (
  id         bigint generated by default as identity primary key,
  student_id uuid not null references students(id) on delete cascade,
  kind       text not null,
  body       text not null,
  screen     text,
  params     jsonb not null default '{}',
  created_at timestamptz not null default now(),
  read_at    timestamptz
);
create table if not exists study_groups (
  id         bigint generated by default as identity primary key,
  kind       text not null check (kind in ('course', 'match')),
  course_id  bigint references courses(id) on delete cascade,
  skill_id   bigint references skills(id) on delete cascade,
  name       text not null,
  created_at timestamptz not null default now()
);
create unique index if not exists one_group_per_course on study_groups (course_id) where kind = 'course';
create table if not exists group_members (
  group_id     bigint not null references study_groups(id) on delete cascade,
  student_id   uuid   not null references students(id) on delete cascade,
  joined_at    timestamptz not null default now(),
  last_read_at timestamptz not null default now(),
  primary key (group_id, student_id)
);
create table if not exists group_messages (
  id        bigint generated by default as identity primary key,
  group_id  bigint not null references study_groups(id) on delete cascade,
  sender_id uuid   not null references students(id) on delete cascade,
  body      text   not null check (length(body) between 1 and 2000),
  sent_at   timestamptz not null default now()
);
create table if not exists study_queue (
  id               bigint generated by default as identity primary key,
  student_id       uuid not null references students(id) on delete cascade,
  course_id        bigint references courses(id) on delete cascade,
  skill_id         bigint references skills(id) on delete cascade,
  created_at       timestamptz not null default now(),
  matched_group_id bigint references study_groups(id) on delete set null,
  check ((course_id is null) <> (skill_id is null))
);

